"""Automation Builder with the **real** Smart Occupancy Detection: both Apps on a Home Assistant OS test system.

    python sod_checks.py [--room kamar_nordur] [--out results.json]

Environment: as for ``haos.py`` (AB_HAOS_URL, AB_HAOS_TOKENS, AB_HAOS_SLUG) plus AB_HAOS_SOD_SLUG, the slug of the
Smart Occupancy Detection App that is paired with the companion integration.

Nothing here simulates occupancy. The room's sensors are test drivers (``input_boolean.kamar_motion`` behind the
PIR, ``input_boolean.nobara_pc`` behind the presence sensor); Smart Occupancy Detection decides, publishes
``binary_sensor.sod_<room>_occupied`` (with ``fresh``), and the automation generated by Automation Builder reacts
to that entity inside Home Assistant:

    Smart Occupancy Detection -> native occupancy entity -> native Home Assistant automation.

The test only shortens Smart Occupancy Detection's *timing settings* for the room (and puts them back); its
detection rules are not touched. The controlled lamp is the "flaky lamp" of ``ha/ab_test_package.yaml``, whose
commands can be dropped to stand for a command that got lost.

The rule is deployed once; then the start-up grace (300 s by default) is waited out, because rechecks do not
correct anything for occupancy changes that soon after a deployment or a start.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
import time
from typing import Any
import urllib.error
import urllib.request

import haos
from haos_checks import App, check, note, results, service, state, wait_state

SOD_SLUG = __import__("os").environ.get("AB_HAOS_SOD_SLUG", "")
LAMP = "light.flaky_lamp"
LUX = "sensor.test_lux"
FAST = {"correlation_window": 5, "exit_confirmation": 20, "inactivity_timeout": 30, "dropout_grace": 5,
        "trigger_stuck_after": 1800, "presence_stuck_after": 0, "startup_hold": 15}


class Stuck(Exception):
    """The room did not reach the state the next step needs."""


class Sod:
    """Smart Occupancy Detection's own interface through Ingress (only to shorten and restore its timing)."""

    def __init__(self) -> None:
        self.base, self.cookie = haos.ingress(SOD_SLUG)

    def call(self, path: str, body: Any = None) -> tuple[int, Any]:
        self.base, self.cookie = haos.ingress(SOD_SLUG)
        headers = {"Content-Type": "application/json", "Cookie": self.cookie, **({"X-SOD": "1"} if body is not None else {})}
        request = urllib.request.Request(f"{self.base}/{path}", data=json.dumps(body).encode() if body is not None else None,
                                         method="POST" if body is not None else "GET", headers=headers)
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                return response.status, json.loads(response.read())
        except urllib.error.HTTPError as err:
            return err.code, err.read().decode(errors="replace")

    def timing(self, timing: dict[str, int]) -> dict[str, int]:
        _, settings = self.call("api/settings")
        before = settings["config"]["timing"] if "config" in settings else settings["timing"]
        status, review = self.call("api/timing/review", {"timing": timing})
        status, saved = self.call("api/timing/save", {"timing": timing, "expected_revision": review["revision"]})
        assert status == 200, saved
        return before

    def room_timing(self, area_id: str, timing: dict[str, int]) -> dict[str, int]:
        """Replace the room's own timing overrides (they win over the global timing). Returns the previous ones."""
        _, view = self.call(f"api/rooms/{area_id}")
        config = view["config"]
        before = dict(config.get("timing") or {})
        status, saved = self.call("api/rooms/save", {"area_id": area_id, "room": {**config, "timing": timing},
                                                     "expected_revision": view["revision"]})
        assert status == 200, saved
        return before


def occupied(entity: str) -> dict[str, Any]:
    return state(entity)


def set_motion(on: bool) -> None:
    service(f"input_boolean.turn_{'on' if on else 'off'}", "input_boolean.kamar_motion")


def drop(on: bool) -> None:
    service(f"input_boolean.turn_{'on' if on else 'off'}", "input_boolean.drop_commands")


def stays(entity_id: str, wanted: str, seconds: float) -> bool:
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        if state(entity_id)["state"] != wanted:
            return False
        time.sleep(0.5)
    return True


def seconds_until(entity_id: str, wanted: str, timeout: float) -> float | None:
    start = time.monotonic()
    while time.monotonic() - start < timeout:
        if state(entity_id)["state"] == wanted:
            return time.monotonic() - start
        time.sleep(0.2)
    return None


def main() -> int:  # noqa: PLR0915 - one linear scenario
    parser = argparse.ArgumentParser()
    parser.add_argument("--room", default="kamar_nordur")
    parser.add_argument("--out", default="")
    parser.add_argument("--skip-grace", action="store_true", help="(for a re-run on an automation deployed long ago)")
    args = parser.parse_args()
    assert haos.SLUG and SOD_SLUG, "set AB_HAOS_SLUG and AB_HAOS_SOD_SLUG"
    occ = f"binary_sensor.sod_{args.room}_occupied"
    other = "binary_sensor.sod_stova_occupied"
    app, sod = App(), Sod()

    def become(on: bool, timeout: float = 150) -> float:
        """Drive the room's sensors and wait for Smart Occupancy Detection's decision."""
        set_motion(on)
        if not on:
            service("input_boolean.turn_off", "input_boolean.nobara_pc")
        took = seconds_until(occ, "on" if on else "off", timeout)
        if took is None:  # everything after this would test nothing
            raise Stuck(f"Smart Occupancy Detection did not report the room {'occupied' if on else 'vacant'} within {timeout:.0f} s: {state(occ)}")
        return took

    # ------------------------------------------------- the real thing is there
    info = haos.sup(f"/addons/{SOD_SLUG}/info")
    entity = occupied(occ)
    check("S0 Smart Occupancy Detection runs as its own App", info["state"] == "started" and info["slug"].endswith("smart_occupancy_detection"), (info["slug"], info["version"], info["state"]))
    check("S0 its occupancy entity comes from the companion integration, with “fresh”", entity["state"] in ("on", "off") and entity["attributes"].get("fresh") is True
          and entity["attributes"].get("device_class") == "occupancy", entity)
    connected = state("binary_sensor.sod_app_connected")
    check("S0 the App is paired and publishing", connected["state"] == "on" and connected["attributes"].get("paired") is True, connected)
    note("S0 versions", f"Smart Occupancy Detection {info['version']}, Automation Builder {haos.sup(f'/addons/{haos.SLUG}/info')['version']}, Core {haos.sup('/core/info')['version']}")
    original_timing = sod.timing(FAST)
    original_room = sod.room_timing(args.room, {})
    try:
        return scenario(app, args, occ, other, become)
    except Stuck as err:
        check("the scenario could not go on", False, err)
        return 1
    finally:
        try:
            sod.room_timing(args.room, original_room)
            sod.timing(original_timing)
            print("Smart Occupancy Detection's timing was put back", flush=True)
        except Exception as err:  # noqa: BLE001
            print(f"COULD NOT restore Smart Occupancy Detection's timing: {err}", flush=True)
        drop(False)


def scenario(app: App, args: Any, occ: str, other: str, become: Any) -> int:  # noqa: PLR0915
    app.overview()
    _, found = app.call("api/entities?purpose=occupancy&q=sod")
    check("S1 the occupancy picker offers Smart Occupancy Detection's entity (as any other binary sensor)", occ in [e["entity_id"] for e in found["results"]], [e["entity_id"] for e in found["results"]][:6])
    drop(False)
    service("input_number.set_value", "input_number.test_lux", value=40)
    become(False, 300)
    check("S1 the room is vacant to begin with (decided by Smart Occupancy Detection)", state(occ)["state"] == "off", state(occ))
    service("light.turn_off", LAMP)
    status, created = app.change("api/devices/create", {"name": "SOD lamp", "targets": [LAMP]})
    device_id = created["device_id"]
    automation_id = f"automation_builder_{device_id}"
    recheck = {"enabled": True, "first_seconds": None, "second_seconds": None, "periodic_minutes": 1, "override_entity": None}
    status, on_rule = app.change("api/rules/save", {"device_id": device_id, "rule": {
        "name": "Occupied", "enabled": True, "triggers": [{"type": "occupancy", "entity_id": occ, "to": "occupied"}],
        "conditions": {"type": "and", "items": [{"type": "numeric", "entity_id": LUX, "below": 1000, "above": None}]},
        "actions": [{"type": "service", "action": "light.turn_on", "target": "all", "data": {}}], "recheck": recheck}})
    status, off_rule = app.change("api/rules/save", {"device_id": device_id, "rule": {
        "name": "Vacant", "enabled": True, "triggers": [{"type": "occupancy", "entity_id": occ, "to": "vacant"}],
        "conditions": {"type": "and", "items": []},
        "actions": [{"type": "service", "action": "light.turn_off", "target": "all", "data": {}}], "recheck": recheck}})
    status, plain = app.change("api/rules/save", {"device_id": device_id, "rule": {
        "name": "No occupancy involved", "enabled": True, "triggers": [{"type": "state", "entity_id": "input_select.mood", "to": "Nátt", "from": None, "for_seconds": 0}],
        "conditions": {"type": "and", "items": []},
        "actions": [{"type": "service", "action": "light.turn_off", "target": "all", "data": {}}]}})
    view = app.device(device_id)
    config_yaml = view["yaml"]
    check("S1 rechecks are generated for the two occupancy rules only", config_yaml.count("alias: 'Recheck: ") == 2 and "Recheck: No occupancy involved" not in config_yaml)
    flat = " ".join(config_yaml.replace("''", "'").split())
    check("S1 Automation Builder contains no occupancy logic: the automation only reads the entity's state and “fresh”",
          f"state_attr('{occ}', 'fresh') != false" in flat and "confidence" not in flat and "possible_" not in flat, flat[:300])
    status, deployed = app.deploy(device_id)
    deployed_at = time.monotonic()
    check("S1 one native automation for the three rules is deployed", status == 200 and deployed["deployed"] and len(view["live"]["automations"]) == 1, deployed)

    # ------------------------------------------------- transitions (the rule itself: works at once, no grace involved)
    took = become(True, 30)
    check("S2 vacant -> occupied is decided by Smart Occupancy Detection", took is not None, took)
    check("S2 initial activation: the automation turns the lamp on at the occupancy change", wait_state(LAMP, "on", 5))
    took = become(False, 150)
    check("S2 occupied -> vacant after Smart Occupancy Detection's timeout", took is not None and took > 10, took)
    check("S2 the vacant rule turns the lamp off", wait_state(LAMP, "off", 5))
    service("input_number.set_value", "input_number.test_lux", value=1500)
    time.sleep(1)
    become(True, 30)
    check("S2 conditions: occupied while it is bright does nothing", stays(LAMP, "off", 4))
    become(False, 150)
    service("input_number.set_value", "input_number.test_lux", value=40)

    # ------------------------------------------------- wait out the start-up grace, then the rechecks
    if not args.skip_grace:
        remaining = 305 - (time.monotonic() - deployed_at)
        if remaining > 0:
            print(f"waiting {remaining:.0f} s for the start-up grace after the deployment", flush=True)
            time.sleep(remaining)
    # 2-second recheck: the first command is lost, the command path works again within two seconds
    drop(True)
    time.sleep(1)
    become(True, 30)
    t0 = time.monotonic()
    time.sleep(0.6)
    drop(False)
    took = seconds_until(LAMP, "on", 10)
    check("S3 the first command was lost and the 2-second recheck turned the lamp on", took is not None and took + 0.6 < 9, took)
    note("S3 lamp on after the occupancy change (s)", None if took is None else round(time.monotonic() - t0, 1))
    check("S3 the 15-second and periodic rechecks then find nothing to do (the lamp stays on, no flicker)", stays(LAMP, "on", 20))
    diag = app.device(device_id)["rule_diagnostics"][on_rule["rule_id"]]
    check("S3 the rule's diagnostics show the recheck that repeated the action", (diag.get("rechecks") or 0) >= 1, {k: diag.get(k) for k in ("rechecks", "last_recheck")})
    become(False, 150)
    wait_state(LAMP, "off", 5)
    # 15-second recheck: the command path is down through the 2-second check
    drop(True)
    time.sleep(1)
    become(True, 30)
    t0 = time.monotonic()
    time.sleep(6)
    still_off = state(LAMP)["state"] == "off"
    drop(False)
    took = seconds_until(LAMP, "on", 20)
    total = None if took is None else time.monotonic() - t0
    check("S4 lost through the 2-second check; the 15-second recheck turned the lamp on", still_off and total is not None and 10 <= total <= 22, (still_off, total))
    become(False, 150)
    wait_state(LAMP, "off", 5)
    # periodic reconciliation: down through both rechecks
    drop(True)
    time.sleep(1)
    become(True, 30)
    time.sleep(20)
    still_off = state(LAMP)["state"] == "off"
    drop(False)
    took = seconds_until(LAMP, "on", 75)
    check("S5 lost through both rechecks; the periodic reconciliation (every minute) turned the lamp on", still_off and took is not None, (still_off, took))
    # manual intervention: a person switches the lamp off in the occupied room
    time.sleep(2)
    service("light.turn_off", LAMP)
    check("S6 a manual change is respected: the lamp stays off through the 2 s, 15 s and periodic rechecks", state(occ)["state"] == "on" and stays(LAMP, "off", 80))
    view = app.device(device_id)
    check("S6 the App reports the difference instead of forcing it", any("may have been a person" in m["message"] for m in view["mismatches"]), view["mismatches"])
    took = become(False, 150)
    check("S6 the room becomes vacant; the lamp was off already", took is not None and state(LAMP)["state"] == "off")
    become(True, 30)
    check("S6 the next occupancy turns the lamp on again (the manual change held only for that stay)", wait_state(LAMP, "on", 5))

    # ------------------------------------------------- an occupancy entity that is unavailable
    unavailable = state(other)
    if unavailable["state"] == "unavailable":
        status, extra = app.change("api/rules/save", {"device_id": device_id, "rule": {
            "name": "Other room", "enabled": True, "triggers": [{"type": "occupancy", "entity_id": other, "to": "occupied"}],
            "conditions": {"type": "and", "items": []}, "actions": [{"type": "service", "action": "light.turn_on", "target": "all", "data": {}}]}})
        view = app.device(device_id)
        check("S7 an unavailable occupancy entity of Smart Occupancy Detection is reported as such",
              any(p["code"] == "unavailable_entity" and p["entity_id"] == other for p in view["entity_problems"]), view["entity_problems"])
        app.change("api/rules/delete", {"device_id": device_id, "rule_id": extra["rule_id"]})
    else:
        note("S7 unavailable occupancy entity", f"{other} is {unavailable['state']}: not tested here (the simulated case is in e2e_checks.py 10)")

    # ------------------------------------------------- Smart Occupancy Detection stops: "fresh: false"
    become(False, 150)
    wait_state(LAMP, "off", 5)
    drop(True)
    time.sleep(1)
    become(True, 30)
    haos.sup(f"/addons/{SOD_SLUG}/stop", "post", {}, 120)   # the command is lost AND the detection App goes away
    deadline = time.monotonic() + 240
    while time.monotonic() < deadline and state(occ)["attributes"].get("fresh") is not False and state(occ)["state"] == "on":
        time.sleep(2)
    stale = state(occ)
    check("S8 with Smart Occupancy Detection stopped, its entity says so (fresh: false, or unavailable)",
          stale["attributes"].get("fresh") is False or stale["state"] == "unavailable", stale)
    drop(False)
    check("S8 while the occupancy is not trustworthy, nothing is corrected (two periodic checks pass)", stays(LAMP, "off", 125))
    haos.sup(f"/addons/{SOD_SLUG}/start", "post", {}, 180)
    deadline = time.monotonic() + 240
    while time.monotonic() < deadline and not (state(occ)["attributes"].get("fresh") is True and state(occ)["state"] in ("on", "off")):
        time.sleep(2)
    fresh = state(occ)
    check("S8 Smart Occupancy Detection is back and its entity is fresh again", fresh["attributes"].get("fresh") is True, fresh)
    if fresh["state"] == "on":
        took = seconds_until(LAMP, "on", 130)
        check("S8 ...the room is still occupied: the next periodic check reconciles the lamp", took is not None, took)
    else:
        note("S8 after its restart Smart Occupancy Detection reports the room vacant", "the lamp is off, as the vacant rule wants; nothing to reconcile")
        check("S8 ...and the lamp agrees with the room", stays(LAMP, "off", 5))

    # ------------------------------------------------- Automation Builder stops: the automations do not need it
    become(False, 150)
    wait_state(LAMP, "off", 8)
    haos.app("stop")
    took = become(True, 30)
    check("S9 with Automation Builder stopped, occupancy still turns the lamp on (native automation)", took is not None and wait_state(LAMP, "on", 5))
    took = become(False, 150)
    check("S9 ...and vacancy turns it off", took is not None and wait_state(LAMP, "off", 5))
    haos.app("start")
    check("S9 Automation Builder is back", haos.app_ready())
    app = App()
    check("S9 ...in sync, and its diagnostics caught up with what ran meanwhile", app.wait_sync(device_id) == "in_sync"
          and (app.device(device_id)["rule_diagnostics"][off_rule["rule_id"]].get("executions") or 0) >= 3, app.device(device_id)["rule_diagnostics"][off_rule["rule_id"]])

    # ------------------------------------------------- Home Assistant restarts
    become(True, 30)
    wait_state(LAMP, "on", 5)
    time.sleep(1)
    service("light.turn_off", LAMP)   # occupied room, lamp switched off by a person, then Home Assistant restarts
    time.sleep(2)
    haos.core("restart")
    check("S10 Home Assistant restarted", haos.core_running())
    deadline = time.monotonic() + 240
    while time.monotonic() < deadline and state(occ)["state"] not in ("on", "off"):
        time.sleep(2)
    after = state(occ)
    check("S10 after the restart Smart Occupancy Detection publishes again", after["state"] in ("on", "off") and after["attributes"].get("fresh") is True, after)
    if after["state"] == "on":
        check("S10 the room is still occupied and the lamp a person switched off stays off (start-up grace)", stays(LAMP, "off", 100))
    else:
        note("S10 after the restart the room is vacant", "the manual-off case across a restart could not be observed with an occupied room")
        check("S10 the lamp stays off", stays(LAMP, "off", 20))
    check("S10 Automation Builder reconnected and is in sync", haos.app_ready() and App().wait_sync(device_id) == "in_sync")
    become(False, 150)
    took = become(True, 40)
    check("S10 after the restart the rules work: occupied turns the lamp on", took is not None and wait_state(LAMP, "on", 6))
    become(False, 150)
    check("S10 ...and vacant turns it off", wait_state(LAMP, "off", 8))

    # ------------------------------------------------- clean up
    app = App()
    app.overview()
    status, removed = app.change("api/devices/delete", {"device_id": device_id, "overwrite": False})
    check("S11 clean-up: the device and its automation are removed", status == 200 and removed["removed_automations"] == 1, removed)
    failed = [r for r in results if r["ok"] is False]
    notes = [r for r in results if r["ok"] is None]
    passed = len(results) - len(failed) - len(notes)
    print(f"\n{passed} of {passed + len(failed)} checks passed (real Smart Occupancy Detection)")
    if args.out:
        Path(args.out).write_text(json.dumps({"passed": passed, "failed": len(failed), "results": results}, indent=1))
    _ = automation_id
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
